def escribir():
    rnd = random.Random(2027)
    errores, k = [], 0
    latinas = re.compile(r"[A-Za-z]")
    for s in SETS:
        if s.get("passage") and latinas.search(s["passage"]):
            errores.append(f"letras latinas en una lectura: {s['passage'][:40]}")
        for q in s["qs"]:
            o = q["o"]
            if len(o) != 4 or len(set(o)) != 4:
                errores.append(f"opciones: {q['q'][:50]} → {o}")
                continue
            # Las frases rusas no deben llevar letras latinas camufladas (a, e, o, c, p, x latinas)
            for t in [q["q"]] + o:
                if latinas.search(t) and not re.fullmatch(r"[\d:%. ]+|.*\d.*", t):
                    errores.append(f"letra latina en texto ruso: {t}")
            if not q.get("e"):
                errores.append(f"sin explicación: {q['q'][:50]}")
            buena, dist = o[0], o[1:]
            rnd.shuffle(dist)
            pos = k % 4
            k += 1
            q["o"], q["a"] = dist[:pos] + [buena] + dist[pos:], pos
    if errores:
        raise SystemExit("ERRORES en rusa1_gen:\n" + "\n".join(errores))
    with open(os.path.join(AQUI, "rusa1_a.json"), "w", encoding="utf-8") as f:
        json.dump(SETS, f, ensure_ascii=False, indent=1)
    from collections import Counter
    nq = sum(len(s["qs"]) for s in SETS)
    print(f"rusa1: {len(SETS)} sets, {nq} preguntas")
    print("  por tarea:", dict(Counter(s["task"] for s in SETS for _ in s["qs"])))


if __name__ == "__main__":
    escribir()
